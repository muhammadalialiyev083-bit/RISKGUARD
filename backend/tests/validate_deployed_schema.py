"""Exercise the actual deployed schema with synthetic rows on disposable local PG.

Run with the ordinary application venv:
  python tests/validate_deployed_schema.py postgresql://agent@127.0.0.1:55432/postgres
The script creates and removes its own randomly named database. It never connects
to production and the fixture contains schema and migration names only.
"""
import json
import os
from pathlib import Path
import secrets
import sys
from datetime import date, datetime, timezone
from urllib.parse import urlparse, urlunparse
import uuid

import psycopg2
from psycopg2 import sql
from psycopg2.extras import Json

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
SCHEMA = json.loads((ROOT / 'tests/fixtures/deployed_schema.json').read_text())


def create_schema(conn):
    tables = {}
    for column in SCHEMA['columns']:
        tables.setdefault(column['table'], []).append(column)
    with conn.cursor() as cursor:
        for table, columns in tables.items():
            definitions = []
            for column in columns:
                kind = column['type']
                if kind == 'character varying':
                    kind = f"varchar({column['max_length']})"
                elif kind == 'numeric':
                    kind = f"numeric({column['precision']},{column['scale']})"
                assert kind.split('(')[0] in {'varchar', 'numeric', 'integer', 'bigint', 'smallint',
                    'text', 'boolean', 'jsonb', 'date', 'timestamp with time zone', 'uuid', 'inet'}
                identity = ' GENERATED BY DEFAULT AS IDENTITY' if column['column'] == 'id' and kind in {'integer', 'bigint'} else ''
                null = ' NOT NULL' if column['nullable'] == 'NO' else ''
                definitions.append(sql.SQL('{} {}{}{}').format(sql.Identifier(column['column']),
                    sql.SQL(kind), sql.SQL(identity), sql.SQL(null)))
            cursor.execute(sql.SQL('CREATE TABLE {} ({})').format(sql.Identifier(table), sql.SQL(',').join(definitions)))
        # PG18 exposes NOT NULL as constraints; columns already carry these on PG17.
        for kind in ('p', 'u', 'c', 'f'):
            for constraint in SCHEMA['constraints']:
                if constraint['type'] == kind:
                    cursor.execute(sql.SQL('ALTER TABLE {} ADD CONSTRAINT {} {}').format(
                        sql.Identifier(constraint['table']), sql.Identifier(constraint['name']),
                        sql.SQL(constraint['definition'])))
        cursor.executemany('INSERT INTO django_migrations(app,name,applied) VALUES (%s,%s,%s)',
            [(item['app'], item['name'], datetime(2026, 1, 1, tzinfo=timezone.utc))
             for item in SCHEMA['applied_migrations']])


def synthetic_row(conn, table, **overrides):
    values = {}
    for column in SCHEMA['columns']:
        if column['table'] != table or column['column'] == 'id':
            continue
        name, kind = column['column'], column['type']
        if column['nullable'] == 'YES':
            values[name] = None
        elif kind in {'integer', 'bigint', 'smallint', 'numeric'}:
            values[name] = 1
        elif kind == 'boolean':
            values[name] = False
        elif kind == 'jsonb':
            values[name] = Json({})
        elif kind == 'timestamp with time zone':
            values[name] = datetime(2026, 1, 1, tzinfo=timezone.utc)
        elif kind == 'date':
            values[name] = date(2026, 1, 1)
        else:
            values[name] = 'synthetic'
    values.update(overrides)
    if table == 'core_auditlog':
        values['id'] = str(uuid.uuid4())
    with conn.cursor() as cursor:
        cursor.execute(sql.SQL('INSERT INTO {} ({}) VALUES ({}) RETURNING id').format(
            sql.Identifier(table), sql.SQL(',').join(map(sql.Identifier, values)),
            sql.SQL(',').join(sql.Placeholder() for _ in values)), list(values.values()))
        return cursor.fetchone()[0]


def validate(database_url):
    os.environ.update(DATABASE_URL=database_url, DEBUG='False', SECRET_KEY=secrets.token_urlsafe(48),
                      DJANGO_SETTINGS_MODULE='bcms_backend.settings')
    import django
    django.setup()
    from django.apps import apps
    from django.contrib.auth.hashers import make_password
    from django.contrib.auth.models import Permission
    from django.contrib.contenttypes.models import ContentType
    from django.core.management import call_command
    from django.db import connection, transaction
    from django.db.migrations.executor import MigrationExecutor
    from rest_framework.test import APIClient
    import release

    with psycopg2.connect(database_url) as raw:
        create_schema(raw)
        org = synthetic_row(raw, 'organizations_organization', name='Synthetic retained org')
        service = synthetic_row(raw, 'organizations_service', organization_id=org)
        user_password = secrets.token_urlsafe(32)
        password_hash = make_password(user_password)
        user = synthetic_row(raw, 'authentication_user', username='retained-validation-account',
            password=password_hash, organization_id=org, role='ADMIN', is_active=True)
        process = synthetic_row(raw, 'processes_businessprocess', organization_id=org,
            service_id=service, criticality='HIGH', status='ACTIVE')
        bia = synthetic_row(raw, 'bia_biaassessment', organization_id=org, process_id=process,
            mtpd_hours=8, rto_hours=2, mtpd_seconds=28801, rto_seconds=7201, status='DRAFT')
        synthetic_row(raw, 'bia_biaimpact', bia_id=bia)
        plan = synthetic_row(raw, 'plans_continuityplan', organization_id=org, process_id=process,
            status='PUBLISHED', snapshot=Json({'retained': 'immutable original'}))
        synthetic_row(raw, 'plans_planstep', plan_id=plan)
        synthetic_row(raw, 'engine_recoveryresource', organization_id=org)
        run = synthetic_row(raw, 'engine_schedulerun', organization_id=org,
            input_snapshot=Json({'original': 'retained'}), results=Json({'schedule': 'retained'}))
        with raw.cursor() as cursor:
            cursor.execute('UPDATE plans_continuityplan SET schedule_run_id=%s WHERE id=%s', [run, plan])
        scenario = synthetic_row(raw, 'simulation_scenario', organization_id=org,
            disrupted_asset_ids=Json([]))
        synthetic_row(raw, 'simulation_simulationrun', organization_id=org, scenario_id=scenario)
        synthetic_row(raw, 'core_auditlog', organization_id=org, actor_id=user,
            actor_role_snapshot='ADMIN', before_state=Json({}), after_state=Json({}))

    # Existing metadata is synthetic as well; only new reviewed metadata may be added.
    for model in apps.get_models():
        opts = model._meta
        if (opts.app_label, opts.model_name) in release.NEW_MODELS:
            continue
        ct, _ = ContentType.objects.get_or_create(app_label=opts.app_label, model=opts.model_name)
        for action in opts.default_permissions:
            Permission.objects.get_or_create(content_type=ct, codename=f'{action}_{opts.model_name}',
                defaults={'name': f'Can {action} {opts.verbose_name_raw}'})
    for app, model in [('engine', 'recoveryresource'), ('engine', 'schedulerun'), ('simulation', 'simulationrun')]:
        ContentType.objects.get_or_create(app_label=app, model=model)

    loader = MigrationExecutor(connection).loader
    known = set(loader.applied_migrations) & set(loader.disk_migrations) & set(loader.graph.nodes)
    expected_tables = {m._meta.db_table for m in loader.project_state(nodes=sorted(known)).apps.get_models(include_auto_created=True)
                       if m._meta.managed and not m._meta.proxy}
    assert not (expected_tables - set(connection.introspection.table_names())), ('Missing fixture tables', expected_tables - set(connection.introspection.table_names()))
    assert release.run_gate(connection, MigrationExecutor, transaction.atomic, call_command, check=True) == release.ALLOWED
    # A late adoption mismatch must roll back earlier schema and metadata changes.
    with connection.cursor() as cursor:
        cursor.execute('ALTER TABLE core_auditlog ALTER COLUMN actor_role_snapshot TYPE varchar(19)')
    from apps.core.migration_compat import SchemaAdoptionError
    try:
        release.run_gate(connection, MigrationExecutor, transaction.atomic, call_command)
    except SchemaAdoptionError:
        pass
    else:
        raise AssertionError('Mismatching deployed column was accepted')
    assert set(MigrationExecutor(connection).loader.applied_migrations) == {
        (item['app'], item['name']) for item in SCHEMA['applied_migrations']}
    with connection.cursor() as cursor:
        cursor.execute("SELECT column_name FROM information_schema.columns WHERE table_name='authentication_user'")
        assert 'preferences' not in {row[0] for row in cursor.fetchall()}
        cursor.execute('ALTER TABLE core_auditlog ALTER COLUMN actor_role_snapshot TYPE varchar(20)')
    print('PASS: incompatible schema rejects and atomically rolls back all earlier additions')
    assert release.run_gate(connection, MigrationExecutor, transaction.atomic, call_command) == release.ALLOWED
    assert release.run_gate(connection, MigrationExecutor, transaction.atomic, call_command) == set()
    print('PASS: read-only preflight, atomic migration, exact old-row preservation, repeat startup')

    from apps.authentication.models import User
    from apps.bia.models import BIAAssessment
    from apps.plans.models import Strategy
    from apps.simulation.models import Scenario, Exercise
    from apps.core.models import AuditLog
    assert User.objects.get(pk=user).password == password_hash
    client = APIClient(enforce_csrf_checks=True, HTTP_ORIGIN='https://uzhi.netlify.app',
                       HTTP_REFERER='https://uzhi.netlify.app/')
    token = client.get('/api/v1/auth/csrf', secure=True).data['csrfToken']
    response = client.post('/api/v1/auth/login', {'username': 'retained-validation-account',
        'password': user_password}, format='json', secure=True, HTTP_X_CSRFTOKEN=token)
    assert response.status_code == 200, response.data
    token = client.cookies['csrftoken'].value
    client.credentials(HTTP_X_CSRFTOKEN=token)
    assert client.get('/api/v1/auth/me', secure=True).status_code == 200
    print('PASS: retained password login with real session and CSRF')

    for resource in ['organizations', 'services', 'processes', 'bia', 'plans', 'scenarios',
                     'providers', 'incidents', 'improvement-tasks', 'simulation-runs', 'audit-logs']:
        response = client.get(f'/api/v1/{resource}/', secure=True)
        assert response.status_code == 200, (resource, response.data)
    payloads = {
        'processes': {'name': 'New synthetic process', 'service': service},
        'bia': {'process': process, 'revision': 2, 'rto_hours': 4, 'mtpd_hours': 4},
        'strategies': {'process': process, 'name': 'New synthetic strategy', 'estimated_rto_hours': 1.5, 'estimated_rpo_minutes': 10},
        'plans': {'process': process, 'title': 'New synthetic plan', 'steps': [{'sequence': 1, 'title': 'Recover'}]},
        'risks': {'process': process, 'threat': 'Synthetic outage', 'likelihood': 3, 'impact': 4},
        'scenarios': {'title': 'New synthetic scenario', 'disrupted_asset_ids': [], 'estimated_outage_hours': 1.25},
        'exercises': {'plan': plan, 'exercise_date': '2026-11-11', 'actual_recovery_hours': 0.5},
        'providers': {'name': 'New synthetic provider'},
    }
    created = {}
    for resource, payload in payloads.items():
        response = client.post(f'/api/v1/{resource}/', payload, format='json', secure=True)
        assert response.status_code == 201, (resource, response.data)
        created[resource] = response.data['id']
    response = client.post('/api/v1/controls/', {'risk': created['risks'], 'title': 'Synthetic control'}, format='json', secure=True)
    assert response.status_code == 201, response.data
    assert BIAAssessment.objects.get(pk=created['bia']).rto_seconds == 14400
    assert Strategy.objects.get(pk=created['strategies']).recovery_seconds == 5400
    assert Scenario.objects.get(pk=created['scenarios']).outage_seconds == 4500
    assert Exercise.objects.get(pk=created['exercises']).actual_recovery_seconds == 1800
    old = BIAAssessment.objects.get(pk=bia)
    old.comments = 'Synthetic unrelated update'
    old.save()
    assert old.rto_seconds == 7201 and old.mtpd_seconds == 28801
    assert AuditLog.objects.filter(actor_id=user, action='LOGIN', actor_role_snapshot='ADMIN').exists()
    print('PASS: legacy-table CRUD, new operations, equal RTO/MTPD, seconds synchronization and preserved audit roles')
    response = client.post('/api/v1/auth/logout', {}, format='json', secure=True)
    assert response.status_code == 200
    assert client.get('/api/v1/auth/me', secure=True).status_code in (401, 403)
    print('PASS: logout invalidates session')
    connection.close()


if __name__ == '__main__':
    parsed = urlparse(sys.argv[1])
    if parsed.scheme not in {'postgres', 'postgresql'} or parsed.hostname not in {'localhost', '127.0.0.1'}:
        raise SystemExit('Only a local disposable PostgreSQL server is allowed.')
    database = 'uzhi_validation_' + secrets.token_hex(8)
    admin = psycopg2.connect(sys.argv[1])
    admin.autocommit = True
    try:
        with admin.cursor() as cursor:
            cursor.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(database)))
        validate(urlunparse(parsed._replace(path='/' + database)))
    finally:
        with admin.cursor() as cursor:
            cursor.execute(sql.SQL('DROP DATABASE IF EXISTS {} WITH (FORCE)').format(sql.Identifier(database)))
        admin.close()
